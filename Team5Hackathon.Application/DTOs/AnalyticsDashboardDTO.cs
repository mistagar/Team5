namespace Team5Hackathon.Application.DTOs;

/// <summary>
/// Full analytics dashboard data for the admin/supervisor view.
/// </summary>
public class AnalyticsDashboardDTO
{
    // ?? Volume ??????????????????????????????????????????????????????????????
    public int TotalCalls { get; set; }
    public int ActiveCalls { get; set; }
    public int EndedCalls { get; set; }
    public int TotalUniqueClients { get; set; }

    // ?? Resolution ??????????????????????????????????????????????????????????
    public int IssuesResolved { get; set; }
    public int IssuesPending { get; set; }

    /// <summary>Resolution rate as a percentage (0–100).</summary>
    public double ResolutionRate { get; set; }

    // ?? Satisfaction ????????????????????????????????????????????????????????
    public double? AverageSatisfactionRating { get; set; }

    // ?? Category breakdown (intent) ?????????????????????????????????????????
    /// <summary>
    /// Count of calls per category: network, data, billing, call, sim, other.
    /// Key = category name, Value = count.
    /// </summary>
    public Dictionary<string, int> CallsByCategory { get; set; } = new();

    /// <summary>Percentage share per category (0–100).</summary>
    public Dictionary<string, double> CategoryPercentages { get; set; } = new();

    // ?? Sentiment breakdown ?????????????????????????????????????????????????
    /// <summary>
    /// Count of calls per sentiment: positive, neutral, frustrated, angry.
    /// Key = sentiment name, Value = count.
    /// </summary>
    public Dictionary<string, int> CallsBySentiment { get; set; } = new();

    /// <summary>Percentage share per sentiment (0–100).</summary>
    public Dictionary<string, double> SentimentPercentages { get; set; } = new();

    // ?? Daily call volume (last 30 days) ????????????????????????????????????
    /// <summary>Key = date string (yyyy-MM-dd), Value = call count.</summary>
    public Dictionary<string, int> DailyCallVolume { get; set; } = new();

    // ?? Top unresolved categories ????????????????????????????????????????????
    /// <summary>
    /// Categories with the most unresolved calls, ordered descending.
    /// Key = category name, Value = unresolved count.
    /// </summary>
    public Dictionary<string, int> UnresolvedByCategory { get; set; } = new();

    // ?? Average call duration ????????????????????????????????????????????????
    /// <summary>Average duration of ended calls in minutes.</summary>
    public double? AverageCallDurationMinutes { get; set; }
}
